export type TranslationKey = keyof typeof translations.en;

export function useTranslation() {
  const { language, setLanguage, toggleLanguage } = useLanguageStore();
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
  }, []);

  const currentLang: Language = mounted ? language : 'en';

  const t = (key: TranslationKey | string, fallback?: string): string => {
    const dict = (translations[currentLang] || translations.en) as Record<string, string>;
    const defaultDict = translations.en as Record<string, string>;
    return dict[key] || defaultDict[key] || fallback || key;
  };

  return {
    language: currentLang,
    setLanguage,
    toggleLanguage,
    t,
    isKhmer: currentLang === 'km',
  };
}
